"""outbox: locked_until — аренда строки на время доставки

Revision ID: 0021
Revises: 0020
Create Date: 2026-08-09

Issue #134, ADR-016. До этой миграции строку на время доставки держала сама
транзакция пачки (`SELECT … FOR UPDATE SKIP LOCKED`), а внутри той же
транзакции шли сетевые вызовы подписчиков: зависший Telegram держал открытую
транзакцию и соединение БД. Теперь доставка идёт вне транзакций, а от второго
диспетчера строку защищает отметка «взято в работу до» — `locked_until`.

Пустое значение — строка свободна. Значение в будущем — событие сейчас
доставляется (или доставлял процесс, который умер: по истечении аренды строка
вернётся в очередь сама). Код снимает аренду в тот же момент, когда пишет исход
доставки, поэтому у доставленных и похороненных строк она всегда пуста —
ручное восстановление по ERR-EVENTS-002 остаётся процедурой на три поля.

Бэкфилла нет и не нужно: пустое значение и есть «свободна», а строки, взятые
воркером старой версии, к моменту применения миграции уже отпущены — старый
воркер останавливается раньше, чем стартует новый (деплой пересоздаёт сервис).

Индекса нет (как и у `next_attempt_at` в 0004): колонка никогда не бывает
единственным условием выборки — она уточняет уже суженный набор
«не доставлено и не похоронено» (NG-8).

Не PII (метка времени доставки) — строки в docs/PII_REGISTRY.md не требует.
"""

