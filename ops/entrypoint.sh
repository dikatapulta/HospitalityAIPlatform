#!/bin/sh
# ENTRYPOINT образа (issue #267): проверки конфигурации ДО запуска команды.
#
# Зачем отдельным шагом, а не только внутри приложения: fail-fast проверка роняет
# ПРОЦЕСС, в котором исполняется, а у uvicorn есть собственные супервизоры —
# `--workers N` в CMD цели `production` и `--reload` в цели `dev`. Там умирает
# ребёнок, родитель остаётся жив и перезапускает его в цикле: контейнер числится
# живым, healthcheck краснеет по таймауту вместо мгновенного падения. Здесь же
# проверка идёт в том процессе, который и станет PID 1 контейнера.
#
# ENTRYPOINT, а не префикс внутри CMD: `command:` в compose переопределяет CMD
# ЦЕЛИКОМ (так делают все сервисы ops/deploy/docker-compose.staging.yml и worker
# в ops/docker-compose.yml), а ENTRYPOINT переживает такой override — проверка не
# теряется ни на одной команде образа. Список самих проверок — не здесь, а в
# src/hospitality/preflight.py: новая добавляется туда и получает это поведение
# автоматически.
#
# `exec` обязателен: без него PID 1 остался бы этим шеллом, и SIGTERM от
# `docker stop` до uvicorn/воркера не дошёл бы — контейнер умирал бы по таймауту
# вместо корректной остановки.
set -e
python -m hospitality.preflight
exec "$@"
