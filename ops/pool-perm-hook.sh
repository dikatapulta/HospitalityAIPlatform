#!/usr/bin/env bash
# Хуки разрешений безголовых окон сторожа (#588, PR 2). Claude Code зовёт их сам: файл
# настроек ops/pool-worker-settings.json сторож передаёт только своим окнам (--settings),
# путь к этому скрипту — в POOL_HOOK. Окна в панели и терминале хуков не получают.
#
# В режиме auto решает классификатор; его отказ — событие PermissionDenied: хук пишет
# строку в журнал разрешений и отказ не трогает. PermissionRequest приходит, только когда
# окно спросило бы человека (правило ask — платный прогон, scp; опасное rm), а человека
# у безголового окна нет: хук пишет строку, кладёт вопрос основателю файлом в ask/ («блокирует:
# да», шаг 4 «Пул окон», docs/QUEUE.md) и отказывает — окно дописывает зачем и ждёт ответа. PostToolUse по Bash — строка о самостоятельном
# «да» из списка основателя, которое что-то удаляет или закрывает (серверная ветка, копия
# окна, issue): основатель просил видеть их в сводке. Черновик↔ready, перезапуск CI
# и комментарии — каждодневная работа окна, в журнал не идут. Журнал — для сводки
# диспетчера. Тесты — tests/test_pool_perm_hook.py.

set -uo pipefail # без -e: упавший хук не должен ронять ход окна

POOL_DIR="${POOL_DIR:-/tmp/necturn-windows}"
LOG="$POOL_DIR/workers/permissions.log"
WHAT_MAX=200 # длина команды в строке журнала: читать глазами, а не хранить

INPUT="$(cat)"

field() { jq -r "$1 // empty" <<<"$INPUT" 2>/dev/null | tr '\n' ' ' | sed 's/ *$//'; }

# Что окно хотело сделать — одной строкой: команда, файл, адрес или вход инструмента.
what() {
    local w
    w="$(field '.tool_input.command // .tool_input.file_path // .tool_input.url')"
    if [ -z "$w" ]; then w="$(jq -c '.tool_input // {}' <<<"$INPUT" 2>/dev/null)"; fi
    if [ "${#w}" -gt "$WHAT_MAX" ]; then w="${w:0:$WHAT_MAX}…"; fi
    printf '%s' "$w"
}

log_line() { # вид причина
    mkdir -p "${LOG%/*}"
    printf '%s · окно %s · %s · %s: %s — %s\n' "$(date '+%d.%m %H:%M')" "${POOL_WORKER:-?}" \
        "$1" "$(field .tool_name)" "$(what)" "$2" >>"$LOG"
}

# Вопрос основателю по шагу 4 «Пул окон»: имя — от окна и действия, поэтому повтор того же
# действия вопрос не множит и дописанное окном не затирает.
ask_founder() {
    local worker name file
    worker="$(printf '%s' "${POOL_WORKER:-x}" | tr -c 'A-Za-z0-9._-' '_')"
    name="perm-${worker}-$(printf '%s %s' "$(field .tool_name)" "$(what)" | cksum | cut -d' ' -f1)"
    file="$POOL_DIR/ask/${name}.md"
    mkdir -p "${file%/*}"
    if [ ! -f "$file" ]; then
        printf '%s\n' "Безголовое окно ${worker} · запрос разрешения · $(date '+%d.%m %H:%M')" "" \
            "Окно хочет: $(field .tool_name): $(what)" \
            "Почему к тебе: это решает только основатель — правило ask (платный прогон или scp) либо опасное удаление (#588). Хук отказал, окно ждёт ответа." \
            "Если «да» — само действие сделает окно с человеком: ответ в файле классификатор не читает." \
            "Работу, зачем это нужно и что будет без этого — окно допишет ниже." "" "блокирует: да" "" >"$file"
    fi
    printf 'Это действие решает только основатель (правило ask — платный прогон или scp — либо опасное удаление), а у безголового окна спросить некого, поэтому отказано. Вопрос основателю уже записан: %s. Допиши в этот файл работу и PR, зачем действие нужно и что будет без него (платный прогон — план и цена по CLAUDE.md), затем ops/pool.sh wait answer %s в фоне. Ответ «да» классификатор не прочтёт: после «да» действие делает окно с человеком — комментарий «Передача» в issue. Действие не повторяй. Можно обойтись без него — удали этот файл и продолжай.' "$file" "$name"
}

# Удалить серверную ветку, убрать копию окна, закрыть issue — в любом месте команды.
SELF_YES='git( -C [^ ]+)? push [^;&|]*(--delete|[[:space:]]-d[[:space:]]|[[:space:]]:[^ ])|git( -C [^ ]+)? worktree remove|gh issue close'

case "${1:-}" in
denied)
    log_line "отказ классификатора" "$(field .reason)"
    ;;
done)
    if grep -qE "$SELF_YES" <<<"$(field .tool_input.command)"; then
        log_line "сам разрешил" "по списку основателя (#588)"
    fi
    ;;
request)
    log_line "к основателю" "отказано хуком, вопрос основателю — файлом в ask/"
    jq -n --arg m "$(ask_founder)" \
        '{hookSpecificOutput: {hookEventName: "PermissionRequest", decision: {behavior: "deny", message: $m}}}'
    ;;
*)
    echo "использование: ops/pool-perm-hook.sh denied | request | done (вход — JSON события на stdin)" >&2
    exit 2
    ;;
esac
exit 0
