# Знаки, которых не вынесет имя файла в «Сохранить как» на Windows и macOS.
_FILENAME_UNSAFE: Final = re.compile(r'[\\/:*?"<>|\x00-\x1f]')


def act_filename(act: ActDocument, extension: str) -> str:
    """«АВР № 15 от 11.11.2026.xlsx»; знаки, недопустимые в имени файла, — дефис."""
    number = _FILENAME_UNSAFE.sub("-", act.number)
    return f"АВР № {number} от {act.composed_on:%d.%m.%Y}.{extension}"


def party_line(label: str, party: ActParty) -> str:
    """«Заказчик: полное наименование, адрес, данные о средствах связи» — пустое пропускается."""
    details = ", ".join(part for part in (party.name, party.address, party.contact) if part)
    return f"{label}: {details}"


def contract_line(act: ActDocument) -> str:
    """«Договор (контракт): № 12 от 01.11.2026»; не задан — пустой бланк формы."""
    return f"{CONTRACT_LABEL}: {act.contract or BLANK_CONTRACT}"
