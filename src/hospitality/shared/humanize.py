"""Числа и даты словами по-русски — надписи, общие у кабинета и канала.

Заведено сводкой дня (spec 0035): одни и те же два числа показывают ДВЕ
поверхности — страница кабинета (`staff_portal/summary.py`) и утреннее
сообщение в Telegram (`channels/telegram/daily_summary.py`). Обе живут в
композиционном слое сиблингами, а импортировать друг друга им нельзя
(контракт 7 import-linter закрывает `staff_portal` от каналов), поэтому
единственное общее место для формулировки — kernel: kernel видят оба.

Здесь именно ФОРМУЛИРОВКА, а не расчёт: сами числа считают их владельцы
(P-5). Правило «эта дата пишется как „19 августа“, а эта длительность — как
„6 мин“» обязано быть одним (P-12): разойдясь, плитка «Берут в работу 6 мин»
и строка «половину взяли быстрее чем за 6 минут» станут для менеджера двумя
разными числами.

Не всякая длительность в интерфейсе — эта: возраст заявки в очереди кабинета
(`staff_portal/queue.py::_age_label`, «только что» и «2 дн») и возраст в
напоминании службе (`channels/telegram/reminders.py::_humanized_age`, «5 дн 3 ч»)
намеренно грубее и точнее соответственно — у них своя поверхность и свой
читатель. Сюда переезжает то, что показывают ДВЕ поверхности сразу.
"""

from __future__ import annotations

from datetime import date
from typing import Final

# Месяцы в родительном падеже: «29 августа». `%B` дал бы именительный
# («август») и зависел бы от локали процесса, которой в контейнере нет.
_MONTHS_GENITIVE: Final = (
    "января",
    "февраля",
    "марта",
    "апреля",
    "мая",
    "июня",
    "июля",
    "августа",
    "сентября",
    "октября",
    "ноября",
    "декабря",
)


def month_day_ru(day: date) -> str:
    """Дата словами без года — «29 августа».

    Год не пишется намеренно: обе поверхности показывают вчера или сегодня, и
    «2026» в них — шум. Понадобится дата постарше — это будет другая функция.
    """
    return f"{day.day} {_MONTHS_GENITIVE[day.month - 1]}"


def duration_label_ru(seconds: int) -> str:
    """Длительность грубо и по-русски: «40 сек», «6 мин», «2 ч».

    Округление ВНИЗ до крупной единицы: «6 мин» читается сразу, «6 мин 43 сек»
    требует деления в уме и точности, которой у медианы по дневной выборке нет.
    Отрицательное (часы переведены назад между двумя чтениями) показывается как
    «0 сек», а не минусом: минус на плитке читался бы как поломка.
    """
    seconds = max(seconds, 0)
    if seconds < 60:
        return f"{seconds} сек"
    minutes = seconds // 60
    if minutes < 60:
        return f"{minutes} мин"
    return f"{minutes // 60} ч"
